import 'app_locale.dart';

/// Translates [english] (used as the lookup key, so call sites read like
/// plain UI copy) into the current [AppLocale], substituting any `{name}`
/// placeholders from [args]. Falls back to the English source text for any
/// key missing from a translation table, or for English itself.
///
/// Brand/place names ("HERE", "Sector 62, Noida") are deliberately left
/// untranslated at their call sites, matching how brand names normally
/// aren't retranslated in real apps.
String t(String english, [Map<String, Object?>? args]) {
  final code = AppLocale.current.value.languageCode;
  var template = code == 'en' ? english : (_translations[code]?[english] ?? english);
  if (args != null) {
    for (final entry in args.entries) {
      template = template.replaceAll('{${entry.key}}', '${entry.value}');
    }
  }
  return template;
}

